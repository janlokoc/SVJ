<p>Data webu patří Vašemu společenství. V administraci si kdykoli stáhnete <strong>export všech dat</strong> a <strong>smlouvu o zpracování osobních údajů</strong> předvyplněnou údaji společenství – obojí patří do dokumentace GDPR, kterou výbor jako správce osobních údajů vede.</p>

<h2>1. Otevřete Data a smlouva</h2>
<p>V administraci zvolte <strong>Správa webu → Data a smlouva</strong> (odkaz je i nahoře v Nastavení).</p>
<?= help_fig('data-1-stranka.jpg', 'Stránka Data a smlouva: export dat a smlouva o zpracování.') ?>

<h2>2. Stáhněte export všech dat</h2>
<ol>
  <li>V části <strong>Export všech dat domu</strong> zadejte své heslo a klikněte na <strong>Stáhnout export (ZIP)</strong>.</li>
  <li>Soubor obsahuje <code>data.json</code> (všechna data webu v otevřeném formátu) a složku <code>uploads</code> s nahranými dokumenty.</li>
  <li>Uložte ho na bezpečné místo – obsahuje osobní údaje obyvatel. Stažení se zapíše do Záznamů.</li>
</ol>
<p class="callout">V edici Zdarma jde export stáhnout jednou za 30 dní – web po stažení napíše, kdy bude možný další.</p>

<h2>3. Smlouva o zpracování osobních údajů</h2>
<ol>
  <li>Zkontrolujte, že máte v <strong>Nastavení</strong> vyplněné IČO a adresu společenství – smlouva je přebírá.</li>
  <li>Klikněte na <strong>Zobrazit smlouvu k tisku</strong> a pak na <strong>Vytisknout / uložit jako PDF</strong>.</li>
  <li>Smlouva platí už přijetím obchodních podmínek při založení webu; výtisk (případně podepsaný předsedou) založte do dokumentace GDPR společenství.</li>
</ol>
<?= help_fig('data-2-smlouva.jpg', 'Smlouva předvyplněná údaji společenství a provozovatele.') ?>

<h2>Dobré vědět</h2>
<ul>
  <li>Jak službu zabezpečujeme a kde jsou data uložena, popisuje veřejná stránka <strong>Bezpečnost a ochrana dat</strong> (odkaz je na stránce Data a smlouva).</li>
  <li>Své vlastní údaje si každý uživatel stáhne sám v <strong>Můj účet → Moje údaje a soukromí</strong>.</li>
</ul>
