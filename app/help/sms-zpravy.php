<h2>3. Odešlete</h2>
<p>Tlačítkem <strong>Odeslat … vlastníkům</strong> zprávu pošlete. Pokud by kredit nestačil na všechny příjemce, web odeslání nenabídne a u náhledu nabídne <strong>Dobít kredit</strong>. Za zprávu, kterou brána odmítne, se peníze do kreditu vrátí. Přehled odeslaných zpráv je dole na stránce.</p>

<h2>Dobré vědět</h2>
<ul>
  <li><strong>Komu SMS přijde:</strong> vlastníkům s aktivním účtem na webu, kteří mají vyplněný mobil (české nebo slovenské číslo). Pevné linky a neplatná čísla web vynechá a napíše, kolik jich je – opravíte je v části Uživatelé.</li>
  <li><strong>Odpověď</strong> na SMS na web nepřijde. Pro delší sdělení pošlete e-mail nebo oznámení a SMS použijte jen jako upozornění.</li>
  <li>SMS posílá web přes smluvní SMS bránu provozovatele služby; čísla vlastníků se jí předávají jen kvůli doručení zprávy.</li>
</ul>
<p class="hint">Doručení SMS do skutečného telefonu ověřovací běh nezkouší – nesmí posílat skutečné SMS. Zprávy v něm přijala zkušební brána se stejným rozhraním, jaké má smluvní brána; ověřeno je vše na straně webu (cena, kredit, příjemci, odeslání a vrácení peněz).</p>
