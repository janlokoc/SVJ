<p>Při havárii, odstávce vody nebo uzavřeném vchodu se vyplatí, aby se to vlastníci dozvěděli hned – i ti, kdo e-maily nečtou. Web jim pošle zprávu jako <strong>SMS na mobil</strong>, který mají vyplněný ve svém účtu.</p>

<h2>1. Kredit</h2>
<p>SMS se platí podle počtu odeslaných zpráv. V administraci otevřete <strong>SMS zprávy</strong>: v části <strong>Kredit</strong> vidíte, kolik SMS Vám zbývá, a cenu jedné SMS. Kredit objednáte tlačítkem <strong>Objednat kredit</strong> – objednávka přijde provozovateli služby a kredit se připíše po zaplacení. Kredit nepropadá.</p>

<h2>2. Napište zprávu a podívejte se na náhled</h2>
<ol>
  <li>Do pole <strong>Text zprávy</strong> napište krátké sdělení a na konec připište, kdo ho posílá (např. „Výbor SVJ Zahradní 12“).</li>
  <li>Nechte zaškrtnuté <strong>Odstranit diakritiku</strong>: zpráva bez háčků a čárek se vejde do 160 znaků, s nimi jen do 70 – a delší zpráva se rozdělí na více SMS, z nichž se každá platí.</li>
  <li>Klikněte na <strong>Náhled a cena</strong>. Uvidíte text tak, jak odejde, počet SMS na jednoho příjemce, počet příjemců a celkovou cenu.</li>
</ol>

<h2>3. Odešlete</h2>
<p>Tlačítkem <strong>Odeslat … vlastníkům</strong> zprávu pošlete. Pokud by kredit nestačil na všechny příjemce, web nepošle nic a upozorní Vás. Zpráva, kterou se nepodaří doručit bráně, se do kreditu vrací. Přehled odeslaných zpráv je dole na stránce.</p>

<h2>Dobré vědět</h2>
<ul>
  <li><strong>Komu SMS přijde:</strong> vlastníkům s aktivním účtem na webu, kteří mají vyplněný mobil (české nebo slovenské číslo). Pevné linky a neplatná čísla web vynechá a napíše, kolik jich je – opravíte je v části Uživatelé.</li>
  <li><strong>Odpověď</strong> na SMS na web nepřijde. Pro delší sdělení pošlete e-mail nebo oznámení a SMS použijte jen jako upozornění.</li>
  <li>SMS posílá web přes smluvní SMS bránu provozovatele služby; čísla vlastníků se jí předávají jen kvůli doručení zprávy.</li>
</ul>
