<p>Při havárii, odstávce vody nebo uzavřeném vchodu se vyplatí, aby se to vlastníci dozvěděli hned – i ti, kdo e-maily nečtou. Web jim pošle zprávu jako <strong>SMS na mobil</strong>, který mají vyplněný ve svém účtu.</p>

<h2>1. Kolik to stojí a z čeho se platí</h2>
<ul>
  <li>Jedna SMS stojí <strong>1,50 Kč bez DPH</strong> a platí se z <strong>kreditu služeb</strong> domu (Administrace → Kredit služeb).</li>
  <li>Edice Premium má <strong>100 SMS ročně v ceně</strong> – čerpají se jako první, teprve potom se platí z kreditu.</li>
  <li>V části <strong>Placení</strong> na stránce SMS zprávy vidíte, kolik SMS teď můžete poslat (SMS v ceně edice a zůstatek kreditu).</li>
</ul>
<p>Kredit dobijete na stránce <strong>Kredit služeb</strong>: zvolte částku a klikněte na <strong>Objednat dobití</strong>. Dostanete zálohovou fakturu s QR kódem; po zaplacení klikněte na <strong>Platbu jsem odeslal(a)</strong>. Kredit se připíše, jakmile provozovatel platbu potvrdí, a platí 24 měsíců od dobití.</p>

<h2>2. Napište zprávu a podívejte se na náhled</h2>
<ol>
  <li>Do pole <strong>Text zprávy</strong> napište krátké sdělení a na konec připište, kdo ho posílá (např. „Výbor SVJ Zahradní 12“).</li>
  <li>Nechte zaškrtnuté <strong>Odstranit diakritiku</strong>: zpráva bez háčků a čárek se vejde do 160 znaků, s nimi jen do 70 – a delší zpráva se rozdělí na více SMS, z nichž se každá platí.</li>
  <li>Klikněte na <strong>Náhled a cena</strong>. Uvidíte text tak, jak odejde, počet SMS na jednoho příjemce, počet příjemců a celkovou cenu bez DPH.</li>
</ol>
