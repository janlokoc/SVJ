<h2>Dobré vědět</h2>
<ul>
  <li><strong>Každé zařízení zvlášť.</strong> Upozornění zapínáte na každém telefonu nebo počítači samostatně. Vypnout je můžete na jednom zařízení, nebo všude naráz.</li>
  <li><strong>Obsah zprávy</strong> je zašifrovaný pro Váš telefon. Push služba (Apple, Google), přes kterou zpráva jde, ho nevidí.</li>
  <li><strong>Nepřichází nic?</strong> Zkontrolujte, že má prohlížeč nebo web na ploše v nastavení telefonu povolená oznámení, a upozornění na webu vypněte a znovu zapněte.</li>
  <li><strong>E-maily</strong> dál chodí podle nastavení v účtu – upozornění je nenahrazují.</li>
</ul>
