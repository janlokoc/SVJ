<p>Web domu si můžete dát na plochu telefonu jako aplikaci – bez obchodu s aplikacemi a bez instalace. Pak Vám na displej chodí upozornění: nové aktuality, zprávy od výboru a sousedů, změny u Vašich hlášení závad a měsíční spotřeba.</p>

<h2>1. Přidejte si web na plochu</h2>
<h3>iPhone a iPad</h3>
<ol>
  <li>Otevřete web domu v <strong>Safari</strong> a přihlaste se.</li>
  <li>Klepněte na tlačítko <strong>Sdílet</strong> (čtvereček se šipkou nahoru) a zvolte <strong>Přidat na plochu</strong>.</li>
  <li>Potvrďte <strong>Přidat</strong>. Na ploše přibude ikona webu – <strong>dál web otevírejte z ní</strong>.</li>
</ol>
<p class="callout">Na iPhonu a iPadu fungují upozornění jen u webu otevřeného z plochy, a to od iOS 16.4. V Safari bez přidání na plochu je zapnout nejde.</p>
<h3>Android</h3>
<ol>
  <li>Otevřete web domu v <strong>Chrome</strong> a přihlaste se.</li>
  <li>Klepněte na nabídku <strong>⋮</strong> vpravo nahoře a zvolte <strong>Přidat na plochu</strong> nebo <strong>Instalovat aplikaci</strong>.</li>
</ol>
<p class="hint">Na Androidu fungují upozornění i bez přidání na plochu, přímo v Chrome.</p>

<h2>2. Zapněte upozornění</h2>
<p>Na webu otevřete <strong>Můj účet → Upozornění do telefonu</strong> a klepněte na <strong>Zapnout upozornění na tomto zařízení</strong>. Telefon se zeptá, zda upozornění povolit – zvolte <strong>Povolit</strong>.</p>
